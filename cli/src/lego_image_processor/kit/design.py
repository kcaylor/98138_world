"""The official kit 31203 design: a 128x80 grid of kit color keys assembled from 40 sections.

Generated by the maintainer tool (``cli/tools/kit31203``) from the pinned instructions PDF and
shipped as package data. Not affiliated with or endorsed by The LEGO Group.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

from .colors import DATA_DIR, load_kit_color_table
from .inventory import check_kit_id
from .source import SourceDocument

DESIGN_PATH = DATA_DIR / "kit_31203_design.json"
WIDTH, HEIGHT = 128, 80
SECTION_SIZE = 16
SECTION_IMAGE_SIZES = ((154, 154), (154, 153))
# Pinned section pages (spec Clarifications), in build order: column by column, rows 0-4.
SECTION_PAGES: Tuple[int, ...] = (
    22, 24, 26, 28, 30, 36, 38, 40, 42, 44, 52, 54, 56, 58, 60, 66, 68, 70, 72, 74,
    80, 82, 84, 86, 88, 94, 96, 98, 100, 102, 110, 112, 114, 116, 118, 124, 126, 128, 130, 132,
)
LAND_KEY = "lego_white"
_DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"


@dataclass(frozen=True)
class Section:
    col: int
    row: int
    page: int
    image_size: Tuple[int, int]
    placement: Dict[str, float]
    order_check: bool


@dataclass(frozen=True)
class ColorCount:
    key: str
    used: int
    supplied: int
    spare: int
    spare_note: str = "unexplained"


@dataclass(frozen=True)
class DesignGrid:
    source: SourceDocument
    width: int
    height: int
    palette: List[str]
    rows: Tuple[str, ...]
    sections: Tuple[Section, ...]
    overrides: Tuple[Dict[str, Any], ...]
    counts: Tuple[ColorCount, ...]
    classification: Dict[str, Any]

    def color_at(self, x: int, y: int) -> str:
        """Kit color key at position (x, y), top-left origin."""
        if not (0 <= x < self.width and 0 <= y < self.height):
            raise IndexError(f"position ({x}, {y}) outside {self.width}x{self.height}")
        return self.palette[_DIGITS.index(self.rows[y][x])]

    def land_positions(self) -> Set[Tuple[int, int]]:
        """Positions whose color is the land color (white round plates)."""
        code = _DIGITS[self.palette.index(LAND_KEY)]
        return {(x, y) for y, row in enumerate(self.rows) for x, ch in enumerate(row) if ch == code}

    def to_layout(self):
        """The design as a schema 2.0 ``PositionPlacementGrid`` (``source_image="official-31203-design"``).

        White cells are land (1x1 round plate, 6141); every other cell is ocean (1x1 round tile,
        98138). Color names and codes come from ``kit_colors.json``.
        """
        # Imported here: layout imports kit (validator), so a module-level import would be circular.
        from ..layout.grid import CURRENT_SCHEMA_VERSION, PositionPlacementGrid
        from ..layout.position import (LAND_PART_ID, LAND_PART_TYPE, OCEAN_PART_ID,
                                       OCEAN_PART_TYPE, PositionPlacement)

        table = load_kit_color_table()
        positions = []
        for y in range(self.height):
            for x in range(self.width):
                key = self.color_at(x, y)
                color = table.by_key(key)
                land = color.role == "land"
                positions.append(PositionPlacement(
                    x=x, y=y, color_id=key, color_name=color.lego.name,
                    lego_color_code=str(color.lego.id),
                    part_type=LAND_PART_TYPE if land else OCEAN_PART_TYPE,
                    lego_part_id=LAND_PART_ID if land else OCEAN_PART_ID,
                ))
        return PositionPlacementGrid(width=self.width, height=self.height, positions=positions,
                                     source_image="official-31203-design",
                                     schema_version=CURRENT_SCHEMA_VERSION)

    def count(self, key: str) -> ColorCount:
        for c in self.counts:
            if c.key == key:
                return c
        raise KeyError(key)


def _fail(filename: str, rule: str) -> ValueError:
    return ValueError(f"{filename}: {rule}")


def parse_design(data: Dict[str, Any], filename: str = "kit_31203_design.json") -> DesignGrid:
    """Parse and validate a design document (data-model.md DesignGrid and Section rules)."""
    try:
        source = SourceDocument.from_dict(data.get("source"))
    except ValueError as exc:
        raise _fail(filename, str(exc)) from exc
    if data.get("width") != WIDTH or data.get("height") != HEIGHT:
        raise _fail(filename, f"width x height must be {WIDTH}x{HEIGHT}")

    kit_keys = [c.key for c in load_kit_color_table().colors]
    palette = data.get("palette")
    if not isinstance(palette, list) or sorted(palette) != sorted(kit_keys):
        raise _fail(filename, "palette must list the 10 kit color keys exactly once")

    rows = data.get("rows")
    if not isinstance(rows, list) or len(rows) != HEIGHT:
        raise _fail(filename, f"expected {HEIGHT} rows")
    valid = set(_DIGITS[: len(palette)])
    for y, row in enumerate(rows):
        if not isinstance(row, str) or len(row) != WIDTH:
            raise _fail(filename, f"rows[{y}] must be a string of {WIDTH} characters")
        bad = set(row) - valid
        if bad:
            raise _fail(filename, f"rows[{y}] has codes {sorted(bad)} outside the palette")
    used = {key: sum(r.count(_DIGITS[i]) for r in rows) for i, key in enumerate(palette)}
    if sum(1 for n in used.values() if n) != len(kit_keys):
        raise _fail(filename, f"the grid must use exactly 10 distinct colors, found "
                              f"{sum(1 for n in used.values() if n)}")

    raw_sections = data.get("sections")
    if not isinstance(raw_sections, list) or len(raw_sections) != len(SECTION_PAGES):
        raise _fail(filename, f"expected {len(SECTION_PAGES)} sections")
    sections = []
    for i, s in enumerate(raw_sections):
        size = tuple(s.get("image_size") or ())
        if size not in SECTION_IMAGE_SIZES:
            raise _fail(filename, f"sections[{i}]: image_size must be 154x154 or 154x153")
        if s.get("order_check") is not True:
            raise _fail(filename, f"sections[{i}]: order_check must be true")
        col, row = s.get("col"), s.get("row")
        if col not in range(WIDTH // SECTION_SIZE) or row not in range(HEIGHT // SECTION_SIZE):
            raise _fail(filename, f"sections[{i}]: col/row out of range")
        sections.append(Section(col=col, row=row, page=s.get("page"), image_size=size,
                                placement=dict(s.get("placement") or {}), order_check=True))
    if len({(s.col, s.row) for s in sections}) != len(sections):
        raise _fail(filename, "section (col,row) pairs must be unique")
    if sorted(s.page for s in sections) != sorted(SECTION_PAGES):
        raise _fail(filename, "section pages must equal the pinned section pages")
    if sorted(source.pages) != sorted(SECTION_PAGES):
        raise _fail(filename, "source.pages must equal the pinned section pages")

    raw_counts = data.get("counts")
    if not isinstance(raw_counts, list) or [c.get("key") for c in raw_counts] != palette:
        raise _fail(filename, "counts must list every palette key in palette order")
    counts = []
    for c in raw_counts:
        if c.get("used") != used[c["key"]]:
            raise _fail(filename, f"counts {c['key']}: used {c.get('used')} != {used[c['key']]} in the grid")
        if c.get("spare") != c.get("supplied", 0) - c["used"] or c["spare"] < 0:
            raise _fail(filename, f"counts {c['key']}: spare must be supplied - used and >= 0")
        counts.append(ColorCount(key=c["key"], used=c["used"], supplied=c["supplied"],
                                 spare=c["spare"], spare_note=c.get("spare_note", "unexplained")))
    if sum(c.used for c in counts) != WIDTH * HEIGHT:
        raise _fail(filename, f"sum of used counts must be {WIDTH * HEIGHT}")

    cl = data.get("classification")
    if not isinstance(cl, dict) or cl.get("flagged") != cl.get("resolved"):
        raise _fail(filename, "classification: flagged must equal resolved")
    overrides = data.get("overrides")
    if not isinstance(overrides, list):
        raise _fail(filename, "overrides must be a list")
    return DesignGrid(
        source=source, width=WIDTH, height=HEIGHT, palette=list(palette), rows=tuple(rows),
        sections=tuple(sorted(sections, key=lambda s: (s.col, s.row))),
        overrides=tuple(overrides), counts=tuple(counts), classification=dict(cl),
    )


@lru_cache(maxsize=None)
def _load(path: Path) -> DesignGrid:
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return parse_design(data, path.name)


def load_official_design(kit_id: str = "31203", path: Optional[Path] = None) -> DesignGrid:
    """The official design of kit 31203 (cached; package data only, no network)."""
    check_kit_id(kit_id)
    return _load(Path(path) if path else DESIGN_PATH)
